import uuid
from datetime import date, datetime, time
from enum import StrEnum

import sqlalchemy as sa
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import (
    AuthorshipMixin,
    Base,
    TimestampMixin,
    UUIDPrimaryKeyMixin,
    enum_column,
    utc_timestamp,
)


class LeavePayType(StrEnum):
    PAID = "PAID"
    UNPAID = "UNPAID"


class LeaveUnit(StrEnum):
    HOURLY = "HOURLY"
    DAILY = "DAILY"


class LeaveStatus(StrEnum):
    PENDING_ADMIN_1 = "PENDING_ADMIN_1"
    PENDING_ADMIN_2 = "PENDING_ADMIN_2"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    CANCELLED = "CANCELLED"


OPEN_LEAVE_STATUSES = frozenset({LeaveStatus.PENDING_ADMIN_1, LeaveStatus.PENDING_ADMIN_2})
ACTIVE_LEAVE_STATUSES = OPEN_LEAVE_STATUSES | {LeaveStatus.APPROVED}

PAY_TYPE_FA = {LeavePayType.PAID: "با حقوق", LeavePayType.UNPAID: "بی‌حقوق"}
UNIT_FA = {LeaveUnit.HOURLY: "ساعتی", LeaveUnit.DAILY: "روزانه"}
STATUS_FA = {
    LeaveStatus.PENDING_ADMIN_1: "در انتظار بررسی منشی",
    LeaveStatus.PENDING_ADMIN_2: "در انتظار تأیید مدیر",
    LeaveStatus.APPROVED: "تأیید شده ✅",
    LeaveStatus.REJECTED: "رد شده ❌",
    LeaveStatus.CANCELLED: "لغو شده",
}


class LeaveRequest(UUIDPrimaryKeyMixin, TimestampMixin, AuthorshipMixin, Base):
    __tablename__ = "leave_requests"
    __table_args__ = (
        sa.CheckConstraint("end_date >= start_date", name="date_order"),
        sa.Index("ix_leave_requests_user_dates", "user_id", "start_date", "end_date"),
    )

    # Short human-friendly number shown in messages (UUIDs are unreadable in chat).
    # Generated by PostgreSQL (identity). SQLite test databases relax it to nullable.
    number: Mapped[int] = mapped_column(sa.Integer, sa.Identity(start=1001), unique=True, nullable=False)
    user_id: Mapped[uuid.UUID] = mapped_column(sa.Uuid, sa.ForeignKey("users.id"), index=True)
    pay_type: Mapped[LeavePayType] = mapped_column(enum_column(LeavePayType))
    unit: Mapped[LeaveUnit] = mapped_column(enum_column(LeaveUnit))
    start_date: Mapped[date] = mapped_column(sa.Date)
    end_date: Mapped[date] = mapped_column(sa.Date)
    start_time: Mapped[time | None] = mapped_column(sa.Time)
    end_time: Mapped[time | None] = mapped_column(sa.Time)
    # Exact interval in UTC, used for overlap checks across hourly and daily requests
    starts_at: Mapped[datetime] = mapped_column(utc_timestamp())
    ends_at: Mapped[datetime] = mapped_column(utc_timestamp())
    duration_minutes: Mapped[int | None] = mapped_column(sa.Integer)
    days_count: Mapped[int | None] = mapped_column(sa.Integer)
    reason: Mapped[str | None] = mapped_column(sa.String(500))
    status: Mapped[LeaveStatus] = mapped_column(enum_column(LeaveStatus), index=True)
    rejection_reason: Mapped[str | None] = mapped_column(sa.String(500))
    submitted_at: Mapped[datetime] = mapped_column(utc_timestamp())
    decided_at: Mapped[datetime | None] = mapped_column(utc_timestamp())

    @property
    def display_number(self) -> str:
        return str(self.number) if self.number is not None else self.id.hex[:6].upper()


class LeaveBalance(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """Prepared for future leave-entitlement rules; not enforced yet."""

    __tablename__ = "leave_balances"
    __table_args__ = (sa.UniqueConstraint("user_id", "jalali_year", "pay_type"),)

    user_id: Mapped[uuid.UUID] = mapped_column(sa.Uuid, sa.ForeignKey("users.id"))
    jalali_year: Mapped[int] = mapped_column(sa.SmallInteger)
    pay_type: Mapped[LeavePayType] = mapped_column(enum_column(LeavePayType))
    entitled_minutes: Mapped[int] = mapped_column(sa.Integer, default=0)
    used_minutes: Mapped[int] = mapped_column(sa.Integer, default=0)
