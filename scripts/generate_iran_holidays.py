"""Regenerate app/domain/attendance/iran_holidays.py from the `holidays` package (dev only).

    pip install holidays
    python scripts/generate_iran_holidays.py 1404 1408 > app/domain/attendance/iran_holidays.py

The package carries Iran's official calendar (lunar holidays as announced, confirmed years only;
later years are its estimates, marked «تخمینی»). Run it once a year when the new official calendar
is out, and review the diff.
"""

import sys

import holidays

sys.path.insert(0, ".")
from app.core.utils.jalali import JalaliDate, to_jalali


def main(first: int, last: int) -> None:
    start = JalaliDate(first, 1, 1).to_gregorian()
    end = JalaliDate(last, 1, 1).to_gregorian()
    found = holidays.Iran(years=range(start.year, end.year + 1), language="fa")
    rows = sorted((d, n) for d, n in found.items() if start <= d < end)
    print('"""Iran\'s official holidays (generated by scripts/generate_iran_holidays.py; do not edit by hand).')
    print()
    print(f"Jalali years {first}–{last - 1}. «تخمینی» marks dates the source only estimates (lunar holidays")
    print("not yet confirmed); config `organization.holidays` / `holiday_exceptions` adjust the list.")
    print('"""')
    print()
    print("from datetime import date")
    print()
    print("IRAN_OFFICIAL_HOLIDAYS: dict[date, str] = {")
    for day, name in rows:
        print(f"    date({day.year}, {day.month}, {day.day}): {name!r},  # {to_jalali(day).iso()}")
    print("}")


if __name__ == "__main__":
    main(int(sys.argv[1]), int(sys.argv[2]))
